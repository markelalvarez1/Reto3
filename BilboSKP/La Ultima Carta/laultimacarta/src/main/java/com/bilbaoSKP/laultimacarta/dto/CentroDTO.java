package com.bilbaoSKP.laultimacarta.dto;

public class CentroDTO {

	private String CIF, nombre, correo, telefono, numeroAlumnos, etapaEducativa, ciudad;

	public String getCIF() {
		return CIF;
	}

	public void setCIF(String cIF) {
		CIF = cIF;
	}

	public String getNombre() {
		return nombre;
	}

	public void setNombre(String nombre) {
		this.nombre = nombre;
	}

	public String getCorreo() {
		return correo;
	}

	public void setCorreo(String correo) {
		this.correo = correo;
	}

	public String getTelefono() {
		return telefono;
	}

	public void setTelefono(String telefono) {
		this.telefono = telefono;
	}

	public String getNumeroAlumnos() {
		return numeroAlumnos;
	}

	public void setNumeroAlumnos(String numeroAlumnos) {
		this.numeroAlumnos = numeroAlumnos;
	}

	public String getEtapaEducativa() {
		return etapaEducativa;
	}

	public void setEtapaEducativa(String etapaEducativa) {
		this.etapaEducativa = etapaEducativa;
	}

	public String getCiudad() {
		return ciudad;
	}

	public void setCiudad(String ciudad) {
		this.ciudad = ciudad;
	}
	
	
}
